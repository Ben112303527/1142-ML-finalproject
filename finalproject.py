# parse
def parse(text):
    parts = text.split("-")

    if len(parts) < 3:
        raise ValueError(f"❌ 格式錯誤：{text}")

    cat = parts[0].strip()
    qty = int(parts[-1])
    item = "-".join(parts[1:-1]).strip()

    return cat, item, qty


# update
def update(inv, action, cat, item, qty):

    if cat not in inv:
        return inv

    if item not in inv[cat]:
        return inv

    if action == "借出零件":
        inv[cat][item] -= qty

    elif action in ["歸還零件", "上架零件"]:
        inv[cat][item] += qty

    elif action == "報廢零件":
        inv[cat][item] -= qty

    return inv

# 讀取資料
data = ws.get_all_values()

for row in data[1:]:
    if len(row) < 3:
        continue

    action = row[1]
    text = row[2]

    try:
        cat, item, qty = parse(text)
        inventory = update(inventory, action, cat, item, qty)

    except:
        pass

# 轉文字
def to_text(inv):
    text = "📦 倉儲狀態\n\n"

    for cat, items in inv.items():
        text += cat + "\n"

        for k, v in items.items():
            text += f"{k} (剩餘：{v})\n"

        text += "\n"

    return text

result = to_text(inventory)

