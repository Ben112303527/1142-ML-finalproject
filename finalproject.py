# 轉文字
def to_text(inv):
    text = "📦 倉儲狀態\n\n"

    for cat, items in inv.items():
        text += cat + "\n"

        for k, v in items.items():
            text += f"{k} (剩餘：{v})\n"

        text += "\n"

    return text

