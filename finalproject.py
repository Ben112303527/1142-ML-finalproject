# 將 inventory dict 轉成文字報表
def to_text(inv):
    text = "📦 倉儲狀態\n\n"

    for cat, items in inv.items(): # 逐類別輸出
        text += cat + "\n"

        for k, v in items.items(): # 逐品項輸出
            text += f"{k} (剩餘：{v})\n"

        text += "\n"

    return text

