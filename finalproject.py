# ======================= parse =======================
# 將表單輸入的字串拆解成：類別 / 品項 / 數量
def parse(text):
    parts = text.split("-")  # 用 "-" 分割字串

    if len(parts) < 3:
        raise ValueError(f"❌ 格式錯誤：{text}")

    cat = parts[0].strip() # 類別 = 第一段
    qty = int(parts[-1]) # 數量 = 最後一段
    item = "-".join(parts[1:-1]).strip() # 使用 join 是因為品項可能本身包含 "-"

    return cat, item, qty


# ======================= update =======================
# 根據操作類型更新 inventory
def update(inv, action, cat, item, qty):

    if cat not in inv: # 如果類別不存在，自動建立
        inv[cat] = {}

# 借出零件 ==============================================
    if action == "借出零件":
        if item in inv[cat]:
            if inv[cat][item] - qty >= 0:
                inv[cat][item] -= qty
            else:
                print(f"⚠️ 借出失敗：{item} 庫存不足")
        else:
            print(f"⚠️ 品項不存在：{item}")

# 歸還零件 ==============================================
    elif action == "歸還零件":
        if item in inv[cat]:
            inv[cat][item] += qty
        else:
            print(f"⚠️ 歸還失敗：{item} 不存在")

# 上架零件 ==============================================
    elif action == "上架零件":
        if item in inv[cat]:
            inv[cat][item] += qty # 若品項已存在，增加數量
        else:
            inv[cat][item] = qty # 若品項不存在，建立新品項

# 報廢零件 ==============================================
    elif action == "報廢零件":
        if item in inv[cat]:
            if inv[cat][item] - qty >= 0:
                inv[cat][item] -= qty
            else:
                print(f"⚠️ 報廢失敗：{item} 庫存不足")
        else:
            print(f"⚠️ 品項不存在：{item}")

    return inv



