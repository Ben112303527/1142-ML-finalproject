# parse
def parse(text):
    parts = text.split("-")

    if len(parts) < 3:
        raise ValueError(f"❌ 格式錯誤：{text}")

    cat = parts[0].strip()
    qty = int(parts[-1])
    item = "-".join(parts[1:-1]).strip()

    return cat, item, qty


# update
def update(inv, action, cat, item, qty):

    if cat not in inv:
        inv[cat] = {}

    if action == "借出零件":
        if item in inv[cat]:
            if inv[cat][item] - qty >= 0:
                inv[cat][item] -= qty
            else:
                print(f"⚠️ 借出失敗：{item} 庫存不足")
        else:
            print(f"⚠️ 品項不存在：{item}")

    elif action == "歸還零件":
        if item in inv[cat]:
            inv[cat][item] += qty
        else:
            print(f"⚠️ 歸還失敗：{item} 不存在")

    elif action == "上架零件":
        if item in inv[cat]:
            inv[cat][item] += qty
        else:
            inv[cat][item] = qty

    elif action == "報廢零件":
        if item in inv[cat]:
            if inv[cat][item] - qty >= 0:
                inv[cat][item] -= qty
            else:
                print(f"⚠️ 報廢失敗：{item} 庫存不足")
        else:
            print(f"⚠️ 品項不存在：{item}")

    return inv

# 讀取資料
